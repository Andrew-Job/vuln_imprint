"""Production YARA-X adapter: compile once, persist compiled DB, scan ELF code only.

Runtime rules deliberately omit ELF header predicates: the host ELF reader
performs platform checks and provides disjoint executable byte ranges. Unlike
whole-file YARA scanning this avoids pattern hits in .rodata / DWARF / notes.
"""
from __future__ import annotations
import hashlib
import importlib
import io
import json
import re
from pathlib import Path


def _file_sha256(path: Path) -> str:
    with path.open("rb") as source:
        return hashlib.file_digest(source, "sha256").hexdigest()


def _load_yara_x():
    """Load the pinned upstream binding; never silently fall back to mocks."""
    try:
        return importlib.import_module("yara_x")
    except ModuleNotFoundError as exc:
        if exc.name != "yara_x":
            raise
        raise RuntimeError(
            "YARA-X is required: build Python binding from pinned source with "
            "scripts/build_yarax_python.sh") from exc


# This subset is deliberately narrower than the full YARA language. Rule files
# generated by Factory must not acquire extra directives through manifest text.
_CVE_ID = re.compile(r"CVE-\d{4}-\d{4,}\Z")
_STATUS = re.compile(r"[A-Za-z0-9_]+\Z")
_HEX_BYTES = re.compile(
    r"(?:[0-9A-Fa-f]{2}|\?\?)(?:\s+(?:[0-9A-Fa-f]{2}|\?\?))*\Z")


def source_from_packs(packs: list[dict]) -> str:
    """Render independent CVE patterns as a deterministic YARA source file.

    Source fields originate in manifests, not executable YARA code. Validate
    their grammar before interpolation so imported metadata cannot inject
    additional rules or conditions.
    """
    output = []
    seen = set()
    for pack in packs:
        if pack.get("platform", {}).get("format") != "ELF":
            raise ValueError("only ELF packs supported by this backend")
        cve = pack.get("cve")
        status = pack.get("status", "RESEARCH_ONLY")
        if not isinstance(cve, str) or not _CVE_ID.fullmatch(cve):
            raise ValueError("invalid CVE identifier in rule source")
        platform = pack.get("platform", {})
        if not isinstance(platform, dict):
            raise ValueError("invalid platform metadata")
        arch = platform.get("arch", "x86-64")
        bits = platform.get("bits", 64)
        if not isinstance(arch, str) or not re.fullmatch(
                r"[A-Za-z0-9_-]{2,40}", arch):
            raise ValueError("invalid architecture identifier")
        if type(bits) is not int or bits not in (32, 64):
            raise ValueError("invalid ELF word size")
        base_name = f"{cve.replace('-', '_')}_ELF{bits}_{arch.replace('-', '_')}"
        # Compiler/optimization, OS and ABI are part of platform identity.
        # Use the canonical ID for the baseline ELF64/x86-64 profile.
        extra = any(
            platform.get(name) not in (None, value)
            for name, value in (("os", "linux"), ("abi", "sysv")))
        extra |= bool(set(platform) - {"format", "arch", "bits", "os", "abi"})
        if extra:
            digest = hashlib.sha256(
                json.dumps(platform, sort_keys=True,
                           separators=(",", ":")).encode()).hexdigest()[:12]
            base_name += f"_{digest}"
        if base_name in seen:
            raise ValueError(f"duplicate rule identifier for {cve}")
        seen.add(base_name)
        if not isinstance(status, str) or not _STATUS.fullmatch(status):
            raise ValueError(f"invalid evidence status for {cve}")
        rules = pack.get("rules")
        if not isinstance(rules, list):
            raise ValueError(f"invalid rule collection for {cve}")
        if not rules:
            continue
        patterns = []
        for rule in rules:
            pattern = rule.get("hex") if isinstance(rule, dict) else None
            if not isinstance(pattern,
                              str) or not _HEX_BYTES.fullmatch(pattern):
                raise ValueError(f"invalid hexadecimal pattern for {cve}")
            patterns.append(" ".join(pattern.upper().split()))
        output.extend([
            f"rule {base_name} {{",
            "  meta:",
            f'    cve = "{cve}"',
            f'    evidence = "{status}"',
            "  strings:",
        ])
        for i, pattern in enumerate(patterns):
            output.append(f"    $v{i} = {{ {pattern} }}")
        output.extend(["  condition:", "    any of them", "}"])
    return "\n".join(output) + "\n"


class YaraXScanner:

    def __init__(self, rules):
        yara_x = _load_yara_x()
        self.yara_x = yara_x
        self.rules = rules
        self.scanner = yara_x.Scanner(rules)

    @classmethod
    def compile(cls, source: str):
        yara_x = _load_yara_x()
        return cls(yara_x.compile(source))

    @classmethod
    def load(cls, path: Path):
        yara_x = _load_yara_x()
        with Path(path).open('rb') as f:
            return cls(yara_x.Rules.deserialize_from(f))

    def save(self, path: Path):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        with Path(path).open('wb') as f:
            self.rules.serialize_into(f)

    def scan(self, path: Path):
        from .elf import ELF
        elf = ELF(Path(path))
        findings = []
        for base, buf in elf.executable_ranges():
            res = self.scanner.scan(buf)
            for rule in res.matching_rules:
                for pattern in rule.patterns:
                    for m in pattern.matches:
                        findings.append({
                            'rule': str(rule.identifier),
                            'pattern': str(pattern.identifier),
                            'file_offset': base + int(m.offset)
                        })
        findings.sort(key=lambda r: (r['file_offset'], r['rule'], r['pattern']))
        return {
            'target': str(path),
            'engine': 'YARA-X/executable-ELF',
            'detected': bool(findings),
            'matches': findings
        }


def compile_database(directory: Path):
    from .database import load_included_packs
    packs = load_included_packs(directory)
    source = source_from_packs(packs)
    target = Path(directory) / 'database-exec.yar'
    target.write_text(source)
    scanner = YaraXScanner.compile(source)
    output = Path(directory) / 'database.compiled'
    scanner.save(output)
    return {
        'pack_count': len(packs),
        'source': str(target),
        'compiled': str(output),
        'sha256': _file_sha256(output)
    }
